const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

;(async () => {
  const { apply } = await import('../src/index.js')
  const tools = new Map()
  const provider = { id: 'test', endpoint: 'https://example.com/v1/generate', model: 'model', apiKeyEnv: 'TEST_KEY', authHeader: 'Authorization', authPrefix: 'Bearer ', imageUrlPath: 'data.0.url', imageBase64Path: 'data.0.b64_json', statusEndpointTemplate: 'https://example.com/v1/tasks/{taskId}', taskIdPath: 'id', statusPath: 'status', videoUrlPath: 'url', errorPath: 'error.message', successStatuses: ['completed'], failureStatuses: ['failed', 'expired'] }
  const get = value => ({ get: () => value })
  const ctx = { inject() {}, get() { return { async saveFileStream({ data }) { for await (const chunk of data) void chunk; return { id: 'file' } } } }, tools: { register(tool) { tools.set(tool.name, tool) } }, credentials: { async resolve() { return { value: 'test-key' } } } }
  const bundle = fs.readFileSync(path.join(__dirname, '../cordis.patch.yml'), 'utf8')
  const bundleTimeout = Number(bundle.match(/^\s+timeoutMs:\s*(\d+)\s*$/m)?.[1])
  assert.equal(bundleTimeout, 300000)
  const config = { imageProviders: get([provider]), videoProviders: get([provider]), defaultImageProvider: get('test'), newApiAccount: get(null), timeoutMs: get(bundleTimeout) }
  apply(ctx, config)
  const generate = tools.get('generate_image')
  const startVideo = tools.get('generate_video')
  const check = tools.get('check_video_task')
  const originalFetch = global.fetch, originalTimeout = AbortSignal.timeout
  const signal = () => new AbortController().signal
  const json = value => new Response(JSON.stringify(value), { headers: { 'content-type': 'application/json' } })
  try {
    let timeoutUsed
    AbortSignal.timeout = ms => { timeoutUsed = ms; return originalTimeout(ms) }
    global.fetch = async () => json({ data: [{ url: 'https://example.com/image.png' }] })
    assert.equal((await generate.execute({ prompt: 'test' }, { signal: signal() })).imageUrl, 'https://example.com/image.png')
    assert.equal(timeoutUsed, 300000)
    config.timeoutMs = get(60000)
    await generate.execute({ prompt: 'test' }, { signal: signal() })
    assert.equal(timeoutUsed, 300000, 'legacy default should migrate to five minutes')
    config.timeoutMs = get(123000)
    await generate.execute({ prompt: 'test' }, { signal: signal() })
    assert.equal(timeoutUsed, 123000, 'custom global timeout remains supported')
    provider.timeoutMs = 40
    await generate.execute({ prompt: 'test' }, { signal: signal() })
    assert.equal(timeoutUsed, 40)
    global.fetch = async (_url, options) => new Response(new ReadableStream({ start(controller) { options.signal.addEventListener('abort', () => controller.error(options.signal.reason), { once: true }) } }), { headers: { 'content-type': 'application/json' } })
    const keepAlive = setTimeout(() => {}, 200)
    await assert.rejects(() => generate.execute({ prompt: 'test' }, { signal: signal() }), /timed out after 40 ms.*may still be running/)
    clearTimeout(keepAlive)
    const controller = new AbortController()
    const cancelled = generate.execute({ prompt: 'test' }, { signal: controller.signal })
    setTimeout(() => controller.abort(new Error('user cancelled')), 5)
    await assert.rejects(() => cancelled, /user cancelled/)
    global.fetch = async () => new Response('{', { headers: { 'content-type': 'application/json' } })
    await assert.rejects(() => generate.execute({ prompt: 'test' }, { signal: signal() }), /invalid JSON/)
    global.fetch = async () => new Response('', { status: 504 })
    await assert.rejects(() => generate.execute({ prompt: 'test' }, { signal: signal() }), /gateway reported a timeout.*may still be running/)
    global.fetch = async () => json({ error: { message: 'model unavailable' } })
    await assert.rejects(() => generate.execute({ prompt: 'test' }, { signal: signal() }), /model unavailable/)
    global.fetch = async () => json({ id: '1', status: 'processing' })
    assert.equal((await startVideo.execute({ provider: 'test', prompt: 'test' }, { signal: signal() })).status, 'processing')
    global.fetch = async () => json({ id: '1' })
    assert.equal((await startVideo.execute({ provider: 'test', prompt: 'test' }, { signal: signal() })).status, 'submitted')
    global.fetch = async () => json({ status: ' COMPLETED ', url: 'https://example.com/video.mp4' })
    assert.equal((await check.execute({ provider: 'test', taskId: '1' }, { signal: signal() })).videoUrl, 'https://example.com/video.mp4')
    global.fetch = async () => json({ status: 'FAILED', error: { message: 'upstream failed' } })
    assert.match((await check.execute({ provider: 'test', taskId: '1' }, { signal: signal() })).message, /upstream failed/)
    global.fetch = async () => json({ status: 'processing', progress: 45 })
    assert.match((await check.execute({ provider: 'test', taskId: '1' }, { signal: signal() })).message, /still processing.*45%/)
    global.fetch = async () => json({ status: 'unexpected' })
    assert.match((await check.execute({ provider: 'test', taskId: '1' }, { signal: signal() })).message, /unrecognized status/)
    provider.protocol = 'newapi-video'
    global.fetch = async url => url.endsWith('/content') ? new Response('', { status: 504 }) : json({ status: 'completed' })
    await assert.rejects(() => check.execute({ provider: 'test', taskId: '1' }, { signal: signal() }), /task 1 completed.*download failed.*timeout.*same task/i)
    global.fetch = async (url, options) => url.endsWith('/content') ? new Response(new ReadableStream({ start(stream) { options.signal.addEventListener('abort', () => stream.error(options.signal.reason), { once: true }) } }), { headers: { 'content-type': 'video/mp4' } }) : json({ status: 'completed' })
    const downloadKeepAlive = setTimeout(() => {}, 200)
    await assert.rejects(() => check.execute({ provider: 'test', taskId: '1' }, { signal: signal() }), /task 1 completed.*download failed.*timed out.*same task/i)
    clearTimeout(downloadKeepAlive)
    console.log('Media timeout and status checks passed.')
  } finally { global.fetch = originalFetch; AbortSignal.timeout = originalTimeout }
})().catch(error => { console.error(error); process.exitCode = 1 })
